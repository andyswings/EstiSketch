def get_style(key: str) -> HomeStyleSpec:
    """Return the :class:`HomeStyleSpec` for ``key`` (defaults to ``craftsman``)."""
    return HOME_STYLES.get(key.strip().lower(), HOME_STYLES["craftsman"])


def list_styles() -> list[HomeStyleSpec]:
    """Return all supported home styles in display order."""
    return list(HOME_STYLES.values())
