"""Blender-side live sync: send edits back to EstiSketch automatically on Ctrl+S.

This module is loaded *inside* Blender by ``estisketch_to_hb5.py`` (by file path, so it must
only depend on the standard library and ``bpy``).  After the EstiSketch scene is built it:

1. imports EstiSketch custom 3D assets (so they are not missing from the Blender scene),
2. tags every generated object and records its baseline pose,
3. saves ``model.blend`` into the session folder (so Ctrl+S never asks for a file name), and
4. installs a ``save_post`` handler that writes ``delta.esk-delta.zip`` into the session folder.

EstiSketch watches the session folder and applies the delta in one undo step.

Units are meters / radians in Blender world space (Z-up).  Object custom properties:

- ``ESTISKETCH_ID``: EstiSketch identifier of the source object.
- ``ESTISKETCH_GEN``: object was generated by the bridge (not user-made).
- ``ESTISKETCH_BASE``: ``[x, y, z, rot_z]`` pose last reported to EstiSketch.
- ``ESTISKETCH_CENTER_OFFSET``: ``[ox, oy]`` object-local offset from the object origin to the
  EstiSketch fixture center (HB5 cabinets/appliances use a back-left corner origin).
- ``ESTISKETCH_Z_OFFSET_M``: level elevation subtracted from exported Z.
"""

from __future__ import annotations

import hashlib
import json
import math
import os
from pathlib import Path
import uuid
import zipfile

DELTA_FILENAME = "delta.esk-delta.zip"
BLEND_FILENAME = "model.blend"
POSE_TOLERANCE = 1e-4
IGNORED_TYPES = frozenset({"CAMERA", "LIGHT", "EMPTY", "SPEAKER", "LIGHT_PROBE"})

_STATE: dict[str, object] = {"sync_dir": "", "plan_center_in": [0.0, 0.0]}


def _as_float_list(raw: object) -> list[float] | None:
    """Convert a list, tuple, or Blender ``IDPropertyArray`` into ``list[float]``."""
    to_list = getattr(raw, "to_list", None)
    if callable(to_list):
        raw = to_list()
    if not isinstance(raw, (list, tuple)):
        return None
    try:
        return [float(v) for v in raw]
    except (TypeError, ValueError):
        return None


def _object_mesh_hash(obj: object) -> str:
    """Deterministic SHA-256 prefix over quantized millimeter local vertex coordinates."""
    if str(getattr(obj, "type", "")).upper() != "MESH":
        return ""
    mesh = getattr(obj, "data", None)
    verts = getattr(mesh, "vertices", None)
    if not verts:
        return ""
    h = hashlib.sha256()
    for v in verts:
        co = getattr(v, "co", (0.0, 0.0, 0.0))
        q = (
            round(float(co[0]) * 1000.0),
            round(float(co[1]) * 1000.0),
            round(float(co[2]) * 1000.0),
        )
        h.update(f"{q[0]},{q[1]},{q[2]};".encode("ascii"))
    return h.hexdigest()[:16]


def center_from_origin(
    loc: tuple[float, float, float],
    rot_z: float,
    offset: tuple[float, float] | None,
) -> tuple[float, float, float]:
    """Return the world center (meters) of an object whose origin is offset from its center.

    Args:
        loc: Object origin in world meters.
        rot_z: Object Z rotation in radians.
        offset: Object-local ``(ox, oy)`` from the origin to the center, in meters.
    """
    if offset is None:
        return (float(loc[0]), float(loc[1]), float(loc[2]))
    ox, oy = offset
    c, s = math.cos(rot_z), math.sin(rot_z)
    return (loc[0] + ox * c - oy * s, loc[1] + ox * s + oy * c, float(loc[2]))


def _pose(obj: object) -> list[float]:
    loc = getattr(obj, "location")
    rot = getattr(obj, "rotation_euler")
    return [float(loc[0]), float(loc[1]), float(loc[2]), float(rot[2])]


def pose_changed(base: object, pose: list[float]) -> bool:
    """True when ``pose`` differs from the recorded ``base`` pose beyond tolerance."""
    vals = _as_float_list(base)
    if vals is None or len(vals) < 4:
        return True
    return any(abs(b - p) > POSE_TOLERANCE for b, p in zip(vals, pose))


def _offset_of(obj: object) -> tuple[float, float] | None:
    vals = _as_float_list(obj.get("ESTISKETCH_CENTER_OFFSET"))  # type: ignore[attr-defined]
    if vals is None or len(vals) < 2:
        return None
    return (vals[0], vals[1])


def classify_object(obj: object) -> str:
    """Classify a scene object for the delta export.

    Returns one of ``"skip"``, ``"mesh_edited"``, ``"moved"``, ``"new"``, or ``"unchanged"``.
    """
    name = str(getattr(obj, "name", ""))
    if "ESTISKETCH_IGNORE" in name or name.startswith("EstiSketch_"):
        return "skip"
    est_id = str(obj.get("ESTISKETCH_ID") or "")  # type: ignore[attr-defined]
    obj_type = str(getattr(obj, "type", "MESH")).upper()
    if est_id:
        old_hash = str(obj.get("ESTISKETCH_MESH_HASH") or "")  # type: ignore[attr-defined]
        new_hash = _object_mesh_hash(obj)
        if old_hash and new_hash and old_hash != new_hash:
            return "mesh_edited"
        if pose_changed(obj.get("ESTISKETCH_BASE"), _pose(obj)):  # type: ignore[attr-defined]
            return "moved"
        return "unchanged"
    if obj.get("ESTISKETCH_GEN"):  # type: ignore[attr-defined]
        return "skip"
    if obj_type in IGNORED_TYPES or getattr(obj, "parent", None) is not None:
        return "skip"
    if obj_type != "MESH":
        return "skip"
    return "new"


def build_entry(obj: object, est_id: str) -> dict[str, object]:
    """Build the ``delta_manifest.json`` entry for ``obj`` (center-based pose in meters)."""
    pose = _pose(obj)
    cx, cy, cz = center_from_origin((pose[0], pose[1], pose[2]), pose[3], _offset_of(obj))
    z_off = float(obj.get("ESTISKETCH_Z_OFFSET_M") or 0.0)  # type: ignore[attr-defined]
    scale = getattr(obj, "scale", (1.0, 1.0, 1.0))
    return {
        "name": str(getattr(obj, "name", "Object")),
        "blender_type": str(getattr(obj, "type", "MESH")).upper(),
        "estisketch_id": est_id,
        "loc_m": [cx, cy, cz - z_off],
        "rot_z_rad": pose[3],
        "scale": [float(scale[0]), float(scale[1]), float(scale[2])],
    }


def _export_glb_bytes(obj: object, tmp_dir: Path) -> bytes | None:
    """Export ``obj`` alone as ``.glb`` at the local origin so the pose is not applied twice."""
    import bpy

    saved_loc = tuple(obj.location)  # type: ignore[attr-defined]
    saved_rot = tuple(obj.rotation_euler)  # type: ignore[attr-defined]
    prev_selected = [o for o in bpy.context.scene.objects if o.select_get()]
    tmp_glb = tmp_dir / f".tmp_{uuid.uuid4().hex}.glb"
    try:
        for other in bpy.context.scene.objects:
            other.select_set(False)
        obj.select_set(True)  # type: ignore[attr-defined]
        obj.location = (0.0, 0.0, 0.0)  # type: ignore[attr-defined]
        obj.rotation_euler = (saved_rot[0], saved_rot[1], 0.0)  # type: ignore[attr-defined]
        bpy.ops.export_scene.gltf(
            filepath=str(tmp_glb),
            export_format="GLB",
            use_selection=True,
            export_apply=True,
        )
        return tmp_glb.read_bytes() if tmp_glb.is_file() else None
    except (RuntimeError, OSError) as exc:
        print(f"EstiSketch: could not export {getattr(obj, 'name', '?')}: {exc}")
        return None
    finally:
        obj.location = saved_loc  # type: ignore[attr-defined]
        obj.rotation_euler = saved_rot  # type: ignore[attr-defined]
        for other in bpy.context.scene.objects:
            other.select_set(other in prev_selected)
        if tmp_glb.is_file():
            tmp_glb.unlink()


def export_delta(sync_dir: str | Path) -> tuple[int, Path | None]:
    """Write ``delta.esk-delta.zip`` for objects moved/added since the last export.

    Returns ``(entry_count, path)``; ``path`` is ``None`` when nothing changed.
    """
    import bpy

    out_dir = Path(sync_dir)
    entries: list[dict[str, object]] = []
    blobs: dict[str, bytes] = {}
    for obj in list(bpy.context.scene.objects):
        kind = classify_object(obj)
        if kind in ("skip", "unchanged"):
            continue
        if kind == "moved":
            entry = build_entry(obj, str(obj.get("ESTISKETCH_ID")))
        elif kind == "mesh_edited":
            est_id = str(obj.get("ESTISKETCH_ID"))
            blob = _export_glb_bytes(obj, out_dir)
            if blob is None:
                continue
            new_hash = _object_mesh_hash(obj)
            entry = build_entry(obj, est_id)
            rel = f"assets/override_{est_id}.glb"
            blobs[rel] = blob
            entry["glb"] = rel
            entry["mesh_modified"] = True
            entry["mesh_hash"] = new_hash
        else:
            blob = _export_glb_bytes(obj, out_dir)
            if blob is None:
                continue
            new_id = f"custom_asset-{uuid.uuid4()}"
            new_hash = _object_mesh_hash(obj)
            entry = build_entry(obj, "")
            rel = f"assets/{new_id}.glb"
            blobs[rel] = blob
            entry["glb"] = rel
            entry["new_estisketch_id"] = new_id
            if new_hash:
                entry["mesh_hash"] = new_hash
        entries.append(entry)
    if not entries:
        return (0, None)

    center = _STATE.get("plan_center_in", [0.0, 0.0])
    manifest = {"schema_version": 1, "plan_center_in": center, "objects": entries}
    tmp_zip = out_dir / f".{DELTA_FILENAME}.tmp"
    with zipfile.ZipFile(tmp_zip, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("delta_manifest.json", json.dumps(manifest, indent=2, sort_keys=True))
        for rel, blob in blobs.items():
            zf.writestr(rel, blob)
    final_zip = out_dir / DELTA_FILENAME
    os.replace(tmp_zip, final_zip)

    # Remember what was sent so repeated saves only report new changes.
    by_name = {o.name: o for o in bpy.context.scene.objects}
    for entry in entries:
        obj = by_name.get(str(entry["name"]))
        if obj is None:
            continue
        new_id = entry.get("new_estisketch_id")
        if new_id:
            obj["ESTISKETCH_ID"] = new_id
        mesh_hash = _object_mesh_hash(obj)
        if mesh_hash:
            obj["ESTISKETCH_MESH_HASH"] = mesh_hash
        obj["ESTISKETCH_BASE"] = _pose(obj)
    return (len(entries), final_zip)


def tag_generated_objects(plan_center_in: tuple[float, float]) -> int:
    """Mark every current object as generated and record baseline poses."""
    import bpy

    _STATE["plan_center_in"] = [float(plan_center_in[0]), float(plan_center_in[1])]
    count = 0
    for obj in bpy.data.objects:
        obj["ESTISKETCH_GEN"] = True
        if obj.get("ESTISKETCH_ID"):
            obj["ESTISKETCH_BASE"] = _pose(obj)
            mesh_hash = _object_mesh_hash(obj)
            if mesh_hash:
                obj["ESTISKETCH_MESH_HASH"] = mesh_hash
        count += 1
    return count


def _show_status(text: str) -> None:
    import bpy

    def _set() -> None:
        try:
            bpy.context.workspace.status_text_set(text)
        except (AttributeError, RuntimeError):
            print(text)

    def _clear() -> None:
        try:
            bpy.context.workspace.status_text_set(None)
        except (AttributeError, RuntimeError):
            pass

    _set()
    bpy.app.timers.register(lambda: (_clear(), None)[1], first_interval=5.0)


def install_save_handler(sync_dir: str | Path) -> None:
    """Save ``model.blend`` into ``sync_dir`` and export a delta after every later save."""
    import bpy
    from bpy.app.handlers import persistent

    _STATE["sync_dir"] = str(sync_dir)
    blend_path = str(Path(sync_dir) / BLEND_FILENAME)
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)

    @persistent
    def _on_save_post(*_args: object) -> None:
        try:
            count, path = export_delta(str(_STATE["sync_dir"]))
        except (RuntimeError, OSError, ValueError) as exc:
            _show_status(f"EstiSketch: could not send changes ({exc})")
            return
        if path is None:
            _show_status("EstiSketch: no changes to send")
        else:
            _show_status(f"EstiSketch: sent {count} change(s) to EstiSketch")

    bpy.app.handlers.save_post[:] = [
        h for h in bpy.app.handlers.save_post if getattr(h, "__name__", "") != "_on_save_post"
    ]
    bpy.app.handlers.save_post.append(_on_save_post)


def import_custom_assets(
    manifest_path: str | Path,
    plan_center_in: tuple[float, float],
    target_collection: object,
) -> int:
    """Import EstiSketch custom ``.glb`` assets listed in ``manifest_path`` into Blender."""
    import bpy

    path = Path(manifest_path)
    if not path.is_file():
        return 0
    items = json.loads(path.read_text(encoding="utf-8"))
    inch_to_m = 0.0254
    imported = 0
    for item in items:
        glb = Path(str(item["glb"]))
        if not glb.is_file():
            print(f"EstiSketch: custom asset file missing: {glb}")
            continue
        before = set(bpy.data.objects.keys())
        bpy.ops.import_scene.gltf(filepath=str(glb))
        created = [o for o in bpy.data.objects if o.name not in before]
        roots = [o for o in created if o.parent is None]
        if not roots:
            continue
        if len(roots) == 1:
            root = roots[0]
        else:
            root = bpy.data.objects.new(str(item.get("name") or "Custom Asset"), None)
            bpy.context.scene.collection.objects.link(root)
            for r in roots:
                r.parent = root
        elev_m = float(item.get("level_elevation_in", 0.0)) * inch_to_m
        x_m = (float(item["x"]) - plan_center_in[0]) * inch_to_m
        y_m = -(float(item["y"]) - plan_center_in[1]) * inch_to_m
        z_m = elev_m + float(item.get("z", 0.0)) * inch_to_m
        root.location = (x_m, y_m, z_m)
        root.rotation_euler = (0.0, 0.0, -math.radians(float(item.get("rotation", 0.0))))
        scale = item.get("scale", [1.0, 1.0, 1.0])
        root.scale = (float(scale[0]), float(scale[1]), float(scale[2]))
        root["ESTISKETCH_ID"] = str(item["identifier"])
        root["ESTISKETCH_Z_OFFSET_M"] = elev_m
        for obj in created + ([root] if root not in created else []):
            for col in list(obj.users_collection):
                col.objects.unlink(obj)
            target_collection.objects.link(obj)  # type: ignore[attr-defined]
        imported += 1
    return imported
